def ai_schema() -> dict[str, Any]:
    """Strict JSON schema for the model (structured output)."""
    field_ref = {"$ref": "#/$defs/field"}
    return {
        "type": "object",
        "additionalProperties": False,
        "required": ["fields", "lines", "is_invoice"],
        "properties": {
            "is_invoice": {"type": "boolean", "description": "False if the document is not an invoice."},
            "fields": {
                "type": "object",
                "additionalProperties": False,
                "required": [f.key for f in FIELDS],
                "properties": {f.key: field_ref for f in FIELDS},
            },
            "lines": {
                "type": "array",
                "items": {
                    "type": "object",
                    "additionalProperties": False,
                    "required": [f.key for f in LINE_FIELDS],
                    "properties": {f.key: field_ref for f in LINE_FIELDS},
                },
            },
        },
        "$defs": {
            "field": {
                "type": "object",
                "additionalProperties": False,
                "required": ["raw", "confidence", "page", "bbox"],
                "properties": {
                    "raw": {
                        "type": ["string", "null"],
                        "description": "Exactly as printed, or null if absent.",
                    },
                    "confidence": {"type": "number", "description": "0 to 1"},
                    "page": {"type": ["integer", "null"], "description": "1-based page number"},
                    "bbox": {
                        "type": ["array", "null"],
                        "items": {"type": "number"},
                        "description": "[x0, y0, x1, y1] as fractions (0-1) of the page width/height",
                    },
                },
            }
        },
    }


SYSTEM_PROMPT = """You extract data from Indian GST invoices (photos, scans or PDFs).
Rules:
- Copy each value EXACTLY as printed (same digits, separators, spelling, date format). Do not
  convert, reformat, calculate or translate anything.
- If a field is not printed on the invoice, return raw = null with confidence 0. Never guess,
  infer, calculate or invent a value, even if it could be derived from other fields.
- confidence (0-1) is how sure you are that you read the printed text correctly.
- page is the 1-based page where the value is printed; bbox is its box on that page as
  fractions of the page size [x0, y0, x1, y1], or null if unsure.
- One entry in `lines` per item row, in printed order. Do not add subtotal/tax rows as items.
- The QR code is decoded separately; do not read it.
- If the document is not an invoice, set is_invoice to false and leave fields null."""


def instructions() -> str:
    hints = [f"- {f.key}: {f.label}" + (f" ({f.hint})" if f.hint else "") for f in FIELDS]
    line_hints = [f"- {f.key}: {f.label}" + (f" ({f.hint})" if f.hint else "") for f in LINE_FIELDS]
    return (
        "Extract these invoice fields:\n" + "\n".join(hints)
        + "\n\nFor every item row, extract:\n" + "\n".join(line_hints)
    )  # fmt: skip


def public_spec() -> dict[str, Any]:
    """For the verification screen."""
    return {
        "sections": [{"key": k, "label": label} for k, label in SECTIONS],
        "fields": [{"key": f.key, "label": f.label, "section": f.section, "type": f.type} for f in FIELDS],
        "line_fields": [{"key": f.key, "label": f.label, "type": f.type} for f in LINE_FIELDS],
    }
